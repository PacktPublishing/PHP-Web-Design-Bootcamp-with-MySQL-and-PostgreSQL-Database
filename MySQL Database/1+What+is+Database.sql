--What is a Database?

--A Database is a place you can store, Manipulate and Retrieve Data.

--This data is often stored inside a computer server

--Facebook is a place we can connect with different people from all over the world.

--All the information stored about us and our friends and also including all our likes and comments are stored inside a database. 
--Once you view a friends pages to check out information about them, the response are coming from database.
--This is same with Amazon, ebay and so on. All the information about any product you check is coming from the database

--In summary, a database is a place you can store, manipulate and retreive data.