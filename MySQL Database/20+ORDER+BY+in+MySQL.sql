--ORDER BY clause sorts the order of a query in ascending or descending order based on which column we listed

SELECT * FROM students
ORDER BY last_name;     --by default they will be arranged in ascending order

SELECT * FROM students
ORDER BY last_name DESC;           --add DESC for descending order

SELECT * FROM students
ORDER BY last_name ASC;           --for ascending order. But this is the default. We don't need to add it.

